// Static documents cannot inherit application CSS. Generate their palette from tokens.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
const root = new URL("../", import.meta.url);
const tokens = readFileSync(new URL("src/tokens.css", root), "utf8");
const values = (name) =>
  [...tokens.matchAll(new RegExp(`--${name}:\\s*([^;]+);`, "g"))].map(
    (m) => m[1],
  );
const [light, dark] = values("canvas");
const [background] = values("action-background");
const [ink] = values("on-action");
const favicon = `<!-- Generated by scripts/sync-brand.mjs from src/tokens.css. -->
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64">
  <rect width="64" height="64" rx="17" fill="${background}"/>
  <path d="M18 17.5c7.2-1.9 12.1-.5 14 3.3 1.9-3.8 6.8-5.2 14-3.3v29c-6.5-1.4-11-.3-14 3-3-3.3-7.5-4.4-14-3v-29Z" fill="none" stroke="${ink}" stroke-width="4" stroke-linejoin="round"/>
  <path d="M32 21v28.5" stroke="${ink}" stroke-width="4"/>
</svg>
`;
const htmlPath = new URL("index.html", root);
const html = readFileSync(htmlPath, "utf8").replace(
  /    <meta name="theme-color"[^>]*\/>\s*(?:<meta name="theme-color"[^>]*\/>\s*)?/,
  `    <meta name="theme-color" content="${light}" media="(prefers-color-scheme: light)" />\n    <meta name="theme-color" content="${dark}" media="(prefers-color-scheme: dark)" />\n    `,
);
for (const [path, value] of [
  [new URL("public/favicon.svg", root), favicon],
  [htmlPath, html],
]) {
  if (process.argv.includes("--check")) {
    if (readFileSync(path, "utf8") !== value)
      throw new Error(
        `Stale palette: ${fileURLToPath(path)}. Run node scripts/sync-brand.mjs.`,
      );
  } else writeFileSync(path, value);
}
